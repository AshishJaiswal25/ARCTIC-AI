// Given a refrigerant and pressure (psig), returns saturation temp (°F)
export function pressureToTemp(refrigerant, pressurePsig) {
  const chart = PT_CHARTS[refrigerant];
  if (!chart) return null;
  const data = chart.data;
  for (let i = 0; i < data.length - 1; i++) {
    const [t1, p1] = data[i];
    const [t2, p2] = data[i + 1];
    if (pressurePsig >= p1 && pressurePsig <= p2) {
      const ratio = (pressurePsig - p1) / (p2 - p1);
      return Math.round((t1 + ratio * (t2 - t1)) * 10) / 10;
    }
  }
  return null;
}

// Given a refrigerant and temperature (°F), returns saturation pressure (psig)
export function tempToPressure(refrigerant, tempF) {
  const chart = PT_CHARTS[refrigerant];
  if (!chart) return null;
  const data = chart.data;
  for (let i = 0; i < data.length - 1; i++) {
    const [t1, p1] = data[i];
    const [t2, p2] = data[i + 1];
    if (tempF >= t1 && tempF <= t2) {
      const ratio = (tempF - t1) / (t2 - t1);
      return Math.round((p1 + ratio * (p2 - p1)) * 10) / 10;
    }
  }
  return null;
}
